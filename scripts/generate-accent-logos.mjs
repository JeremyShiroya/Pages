// Recolours the Pages logo for every accent colour (Settings → Theme) and
// writes the app logos and the Android launcher icons for each.
//
//   node scripts/generate-accent-logos.mjs            → writes everything
//   node scripts/generate-accent-logos.mjs --preview  → one contact sheet only
//
// Each pixel keeps its own shading and anti-aliasing: the purple is swapped
// for the accent in HSL (hue + saturation from the accent, lightness shifted
// by the same amount), in proportion to how purple the pixel was, so the
// white "P" and the soft edges stay exactly as drawn.
import sharp from 'sharp'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

export const ACCENT_LOGOS = {
  purple: null, // the original artwork
  'pastel-purple': '#a685e2',
  'pastel-blue': '#5f9fd8',
  'pastel-pink': '#e2789f',
  'pastel-yellow': '#d4b13e',
  burgundy: '#8c1c3a',
  sage: '#6f8f6a',
  green: '#2ea44f',
  'pastel-green': '#5fb87e',
  mono: '#1c1c1e',
}

const root = resolve(import.meta.dirname, '..')
const res = (p) => resolve(root, 'android/app/src/main/res', p)
const DENSITIES = ['ldpi', 'mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi']

const hexToRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16))
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2
  if (max === min) return [0, 0, l]
  const d = max - min
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  let h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  return [h * 60, s, l]
}
function hslToRgb(h, s, l) {
  const k = (n) => (n + h / 30) % 12
  const a = s * Math.min(l, 1 - l)
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)))
  return [f(0), f(8), f(4)].map((v) => Math.round(Math.max(0, Math.min(1, v)) * 255))
}

// The logo's own purple, measured from the artwork.
const BASE = rgbToHsl(...hexToRgb('#7f22ea'))

async function recolour(file, hex) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  if (!hex) return sharp(data, { raw: info }).png()
  const [th, ts, tl] = rgbToHsl(...hexToRgb(hex))
  for (let i = 0; i < data.length; i += 4) {
    if (!data[i + 3]) continue
    const [h, s, l] = rgbToHsl(data[i], data[i + 1], data[i + 2])
    // How purple this pixel is (0 = white/grey, 1 = full logo purple).
    const hueNear = Math.abs(((h - BASE[0] + 540) % 360) - 180) < 50
    // Ramped, so the faint purple texture inside the white P (a few % of
    // saturation) is left alone instead of being darkened into speckles.
    const raw = hueNear ? Math.min(1, s / BASE[1]) : 0
    // Near-white pixels (the P) are protected by brightness as well.
    const whiteness = Math.max(0, Math.min(1, (l - 0.72) / 0.16))
    const amount = Math.max(0, Math.min(1, (raw - 0.18) / 0.5)) * (1 - whiteness)
    if (amount <= 0.02) continue
    const [r, g, b] = hslToRgb(amount > 0.5 ? th : h, ts * amount + s * (1 - amount), l + (tl - BASE[2]) * amount)
    data[i] = r; data[i + 1] = g; data[i + 2] = b
  }
  return sharp(data, { raw: info }).png()
}

const write = async (image, out) => { mkdirSync(dirname(out), { recursive: true }); await image.toFile(out) }

if (process.argv.includes('--preview')) {
  const tiles = []
  for (const [id, hex] of Object.entries(ACCENT_LOGOS)) {
    tiles.push({ input: await (await recolour(resolve(root, 'public/images/P Logo.png'), hex)).resize(160, 160).toBuffer() })
  }
  const sheet = sharp({ create: { width: 160 * 5, height: 320, channels: 4, background: '#ffffff' } })
    .composite(tiles.map((t, i) => ({ ...t, left: (i % 5) * 160, top: Math.floor(i / 5) * 160 })))
  await sheet.png().toFile(process.argv[process.argv.indexOf('--preview') + 1])
} else {
  for (const [id, hex] of Object.entries(ACCENT_LOGOS)) {
    // In-app logo (top bar, About, What's New).
    await write(await recolour(resolve(root, 'public/images/P Logo.png'), hex), resolve(root, `public/images/logos/${id}.png`))
    if (id === 'purple') continue // the default launcher icon is the existing one
    for (const density of DENSITIES) {
      for (const kind of ['ic_launcher', 'ic_launcher_round', 'ic_launcher_foreground']) {
        await write(await recolour(res(`mipmap-${density}/${kind}.png`), hex), res(`mipmap-${density}/${kind.replace('ic_launcher', `ic_launcher_${id.replace('-', '_')}`)}.png`))
      }
    }
    const name = `ic_launcher_${id.replace('-', '_')}`
    for (const round of ['', '_round']) {
      writeFileSync(res(`mipmap-anydpi-v26/${name}${round}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-accent-logos.mjs -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/${name}_foreground"/>
</adaptive-icon>
`)
    }
  }
  console.log('logos and launcher icons written')
}
