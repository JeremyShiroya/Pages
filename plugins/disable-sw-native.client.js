import { isNativeCapacitorPlatform } from '~/composables/useNativePlatform'

// The PWA service worker is great on the web (installable, offline), but in the
// Capacitor native app it is actively harmful: Capacitor already serves the
// bundled assets locally and offline, so the SW just adds a redundant cache
// layer that serves STALE app bundles — after an APK update (which once shipped
// a removed plugin's old code and broke the whole app on launch) and after a
// live-update bundle switch, where its navigateFallback kept answering with the
// previous build's index.html.
//
// So this plugin owns registration (the PWA module's own client plugin is off,
// see `pwa.client.registerPlugin` in nuxt.config.ts):
//   - web:    register the worker generated by @vite-pwa/nuxt
//   - native: never register; remove any worker an older build left behind,
//             and drop its caches, so every launch runs the bundle actually
//             being served.
export default defineNuxtPlugin(() => {
  if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return

  if (!isNativeCapacitorPlatform()) {
    // sw.js is emitted by @vite-pwa/nuxt for production builds only.
    if (import.meta.dev) return
    window.addEventListener('load', () => {
      navigator.serviceWorker.register('/sw.js', { scope: '/' }).catch(() => {})
    }, { once: true })
    return
  }

  navigator.serviceWorker.getRegistrations()
    .then((registrations) => {
      for (const registration of registrations) registration.unregister()
    })
    .catch(() => {})

  if (typeof caches !== 'undefined') {
    caches.keys()
      .then((keys) => Promise.all(keys.map((key) => caches.delete(key))))
      .catch(() => {})
  }
})
